/**
 * English, Hindi and Urdu retain their established packs. Every active
 * catalogue language now has a core-shell/settings pack; module-specific keys
 * that are not translated yet safely inherit English instead of breaking UI.
 */
export const translations = new Proxy(baseTranslations, {
  get(target, property: string | symbol) {
    if (typeof property !== 'string') return Reflect.get(target, property);
    return target[property] || target.en;
  }
}) as Record<Language, Record<string, string>>;
